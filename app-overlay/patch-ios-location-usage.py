from pathlib import Path
import plistlib

plist_path = Path("ios/App/App/Info.plist")
if not plist_path.exists():
    raise SystemExit("iOS Info.plist was not generated by Capacitor")
with plist_path.open("rb") as f:
    data = plistlib.load(f)
data.setdefault("NSLocationWhenInUseUsageDescription", "يستخدم تطبيق سريع موقعك لتحديد عنوان التوصيل بدقة.")
with plist_path.open("wb") as f:
    plistlib.dump(data, f)
print("Added iOS foreground location usage description.")
